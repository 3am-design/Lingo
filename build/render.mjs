// Renders every locale × page into the HTML files Vite then builds.
//
// The output files are committed so the repo still opens as a plain static
// site, but they are artifacts: edit build/locales/*.mjs for copy and
// build/templates/*.mjs for structure, then re-run `pnpm pages`.

import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { LOCALES, PAGES, localeRoot } from './config.mjs'
import { footer, head, headers } from './templates/chrome.mjs'
import home from './templates/home.mjs'
import faq from './templates/faq.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const bodies = { home, faq }

const BANNER = `    <!-- Generated by build/render.mjs — do not edit.
         Copy lives in build/locales/, structure in build/templates/.
         Regenerate with: pnpm pages -->`

const renderPage = ({ locale, page, t }) => {
  const assets = localeRoot(locale)
  const bodyClass = page.id === 'faq' ? ' class="faq-page"' : ''
  return `<!doctype html>
<html lang="${locale.code}">
  <head>
${BANNER}
${head({ locale, page, t, assets }).replace(/^\n/, '')}
  </head>
  <body${bodyClass}>
${headers({ locale, page, t, assets })}

${bodies[page.id]({ t, assets })}

${footer({ page, t, assets })}
  </body>
</html>
`
}

const run = async () => {
  const written = []
  for (const locale of LOCALES) {
    if (!locale.enabled) continue
    const { default: t } = await import(`./locales/${locale.code}.mjs`)
    for (const page of PAGES) {
      const out = join(root, locale.dir, page.file)
      await mkdir(dirname(out), { recursive: true })
      await writeFile(out, renderPage({ locale, page, t }), 'utf8')
      written.push(join(locale.dir, page.file))
    }
  }
  console.log(`pages: wrote ${written.length} files — ${written.join(', ')}`)
}

run().catch((error) => {
  console.error(error)
  process.exit(1)
})
